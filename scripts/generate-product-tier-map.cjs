#!/usr/bin/env node
/**
 * generate-product-tier-map.cjs
 * Single source of truth: constants/productTierMap.json.
 * Generates two identical TS modules from it so the client (services/) and
 * functions/src (separate tsconfig, can't import across the boundary) never
 * hand-maintain duplicate copies that can drift (see FIXES.md F63).
 *
 * Runs via root `predev`/`prebuild` hooks and functions' `prebuild` hook.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const SOURCE_PATH = path.resolve(__dirname, '../constants/productTierMap.json');
const TARGETS = [
  path.resolve(__dirname, '../constants/productTierMap.ts'),
  path.resolve(__dirname, '../functions/src/generated/productTierMap.ts'),
];

const map = JSON.parse(fs.readFileSync(SOURCE_PATH, 'utf8'));

const output = `\
// AUTO-GENERATED by scripts/generate-product-tier-map.cjs from constants/productTierMap.json
// - do not edit manually. See .claude/audits/FIXES.md F63.

export const PRODUCT_TIER_MAP: Record<string, 'premium' | 'family'> = ${JSON.stringify(map, null, 2)};
`;

for (const target of TARGETS) {
  fs.mkdirSync(path.dirname(target), {recursive: true});
  fs.writeFileSync(target, output, 'utf8');
}

console.log(`✅  productTierMap.ts generated (${Object.keys(map).length} products) → ${TARGETS.length} targets`);
